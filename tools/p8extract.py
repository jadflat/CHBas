"""Turn the BAS cart (assets/bas.p8) into the sketch's data.

    python tools/p8extract.py [--cart assets/bas.p8] [--png out/sheet.png]

Writes Bas/src/assets/Cart.{h,cpp} and Sine.cpp:
- SHEET: the whole 128x128 sprite sheet, packed like gfx_fb (two pixels a
  byte, the left one in the low nibble). BAS draws sprites from all of it.
- COLOURS: for each sprite, a bit for each colour it uses (spr()'s fast path:
  a sprite with no colour palt() makes transparent is copied a row at a time).
- PALETTE: PICO-8's, as RGB565, and its 16 secret colours (128-143) for the
  splash's screen-palette fade.

BAS draws no map and reads no flags. The sound is tools/p8audio.py's.

Deterministic: the same cart gives the same files byte for byte.
"""
import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "Bas" / "src" / "assets"

P8PAL = [0x000000, 0x1D2B53, 0x7E2553, 0x008751, 0xAB5236, 0x5F574F, 0xC2C3C7, 0xFFF1E8,
         0xFF004D, 0xFFA300, 0xFFEC27, 0x00E436, 0x29ADFF, 0x83769C, 0xFF77A8, 0xFFCCAA]

P8SECRET = [0x291814, 0x111D35, 0x422136, 0x125359, 0x742F29, 0x49333B, 0xA28879, 0xF3EF7D,
            0xBE1250, 0xFF6C24, 0xA8E72E, 0x00B543, 0x065AB5, 0x754665, 0xFF6E59, 0xFF9D81]


def sections(text):
    """{name: [lines]} for the cart's __name__ sections."""
    out, cur = {}, None
    for line in text.splitlines():
        m = re.fullmatch(r"__(\w+)__", line.strip())
        if m:
            cur = out.setdefault(m.group(1), [])
        elif cur is not None:
            cur.append(line.rstrip())
    return out


def read_cart(path):
    s = sections(Path(path).read_text(encoding="utf-8"))
    gfx = [[int(ch, 16) for ch in row.ljust(128, "0")[:128]] for row in s["gfx"][:128]]
    gfx += [[0] * 128 for _ in range(128 - len(gfx))]
    mem = bytearray()
    for row in gfx:
        for x in range(0, 128, 2):
            mem.append(row[x] | (row[x + 1] << 4))
    return gfx, bytes(mem), b""


def c_array(name, data, per=32):
    rows = [", ".join(f"0x{b:02X}" for b in data[i:i + per]) for i in range(0, len(data), per)]
    return f"const uint8_t {name}[{len(data)}] = {{\n    " + ",\n    ".join(rows) + "\n};\n"


def write_if_changed(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text(encoding="utf-8") != text:
        path.write_text(text, encoding="utf-8", newline="\n")
        return True
    return False


def colours(mem):
    out = []
    for n in range(256):
        sx, sy = (n % 16) * 8, (n // 16) * 8
        m = 0
        for y in range(8):
            for x in range(8):
                m |= 1 << ((mem[(sy + y) * 64 + (sx + x) // 2] >> (4 * ((sx + x) & 1))) & 15)
        out.append(m)
    return out


def rgb565(c):
    return ((c >> 19) & 0x1F) << 11 | ((c >> 10) & 0x3F) << 5 | ((c >> 3) & 0x1F)


def emit(mem, tiles, cart_name):
    head = f"// GENERATED by tools/p8extract.py from {cart_name}: do not edit.\n"
    pal = ", ".join(f"0x{rgb565(c):04X}" for c in P8PAL + P8SECRET)
    cols = colours(mem)
    h = head + """#pragma once
#include <stdint.h>

namespace cart {
// The whole sprite sheet, 128x128: 64 bytes a row, two pixels a byte (the
// left one in the low nibble, as gfx_fb packs them).
extern const uint8_t SHEET[8192];
// For each sprite, bit c set when the sprite uses colour c.
extern const uint16_t COLOURS[256];
// The PICO-8 palette as RGB565: 0-15, then the secret colours 128-143.
extern const uint16_t PALETTE[32];
}
"""
    cpp = head + '#include "Cart.h"\n\nnamespace cart {\n\n'
    cpp += c_array("SHEET", mem) + "\n"
    rows = [", ".join(f"0x{v:04X}" for v in cols[i:i + 16]) for i in range(0, 256, 16)]
    cpp += "const uint16_t COLOURS[256] = {\n    " + ",\n    ".join(rows) + "\n};\n"
    cpp += f"\nconst uint16_t PALETTE[32] = {{ {pal} }};\n\n}}\n"
    a = write_if_changed(OUT / "Cart.h", h)
    b = write_if_changed(OUT / "Cart.cpp", cpp)
    return emit_sine() or a or b


def emit_sine():
    """A quarter of a sine wave, 256 points in 1/65536ths (Fix.cpp's p8sin/p8cos)."""
    import math
    vals = [round(math.sin(i / 256 * math.pi / 2) * 65536) for i in range(256)]
    rows = [", ".join(str(v) for v in vals[i:i + 16]) for i in range(0, 256, 16)]
    text = ("// GENERATED by tools/p8extract.py: do not edit.\n"
            "// sin(i/256 * pi/2) * 65536 for i = 0..255 (Fix.cpp's p8sin/p8cos).\n"
            '#include <stdint.h>\n\nextern const uint16_t SINE_QUARTER[256] = {\n    '
            + ",\n    ".join(rows) + "\n};\n")
    return write_if_changed(OUT / "Sine.cpp", text)


def render(gfx, png):
    from PIL import Image
    rgb = [((c >> 16) & 255, (c >> 8) & 255, c & 255) for c in P8PAL]
    sheet = Image.new("RGB", (128, 128))
    sheet.putdata([rgb[p] for row in gfx for p in row])
    sheet.resize((512, 512), Image.NEAREST).save(png)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--cart", default=str(ROOT / "assets" / "bas.p8"))
    ap.add_argument("--png")
    a = ap.parse_args(argv)
    gfx, mem, tiles = read_cart(a.cart)
    changed = emit(mem, tiles, Path(a.cart).name)
    print(f"Cart.*: {'written' if changed else 'unchanged'}")
    if a.png:
        render(gfx, a.png)


if __name__ == "__main__":
    main()
